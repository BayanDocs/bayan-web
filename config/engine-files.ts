// The engine's WebAssembly package and the files of it that the app serves (work package WEB-002).
// scripts/engine-package.sh builds the package into engine-package/ from the bayan-core commit pinned in bayan-core.pin. The Vite plugin
// (config/engine-plugin.ts) serves its runtime files under a content-addressed folder, assets/engine-<digest>/, and its licence notices
// under engine-licenses/; scripts/sri.ts, scripts/check-licenses.ts and scripts/check-engine.ts read the same description from here.

import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import type { EngineManifest } from "../src/engine/engine-manifest.ts";

/** Where scripts/engine-package.sh puts the package. */
export const defaultPackageDir = fileURLToPath(new URL("../engine-package", import.meta.url));

/** Where the pinned bayan-core commit is recorded. */
export const pinFile = fileURLToPath(new URL("../bayan-core.pin", import.meta.url));

/**
 * The files the engine runs from: the worker host (the worker's entry script), wasm-bindgen's glue, which the worker host imports,
 * and the module, which the glue fetches. They keep their names, because the worker host imports the glue by a relative path.
 */
export const runtimeFileNames = ["bayan-worker.js", "bayan_wasm.js", "bayan_wasm_bg.wasm"] as const;
export type RuntimeFileName = (typeof runtimeFileNames)[number];

/**
 * The licence notices the package says to distribute with the module: BayanDocs' licence, the notices of the Rust crates compiled into
 * the module, and those of the Rust standard library.
 */
export const noticeFileNames = [
  "THIRD-PARTY-LICENSES.txt",
  "RUST-STANDARD-LIBRARY-COPYRIGHT.html",
  "LICENSES/GPL-3.0-or-later.txt",
  "LICENSES/LicenseRef-BayanDocs-App-Store-Permission.txt",
] as const;

/** The build-relative folder of the licence notices; its path is stable, so operators and the app can link to it. */
export const noticesFolder = "engine-licenses";

/** The TypeScript declarations of the engine protocol, generated by bayan-core from the engine's Rust types. */
export const protocolDeclarations = "engine-protocol.d.ts";

/** Reads the commit from bayan-core.pin or engine-package/BUILT-FROM: exactly one line `commit=<40 lowercase hex digits>`. */
export function parsePin(text: string, source: string): string {
  const commits = text
    .split(/\r?\n/)
    .map((line) => /^commit=([0-9a-f]{40})$/.exec(line)?.[1])
    .filter((commit): commit is string => commit !== undefined);
  const [commit] = commits;
  if (commits.length !== 1 || commit === undefined) {
    throw new Error(`${source} must contain exactly one line commit=<40 lowercase hexadecimal digits>.`);
  }
  return commit;
}

/** The Subresource Integrity form of a file's SHA-384, as integrity attributes and fetch() take it. */
export function integrityOf(bytes: Uint8Array): string {
  return `sha384-${createHash("sha384").update(bytes).digest("base64")}`;
}

export interface EngineFile {
  /** The file's name inside the package. */
  name: string;
  /** Where the built app serves it: a build-relative path with "/" separators, such as assets/engine-…/bayan-worker.js. */
  path: string;
  /** Its Subresource Integrity hash. */
  integrity: string;
  bytes: Uint8Array;
}

export interface EngineBuild {
  /** The bayan-core commit the package was built from. */
  commit: string;
  /** The engine's semantic version, from the package's package.json. */
  version: string;
  /** The runtime files, served from one content-addressed folder: a changed engine always gets a new address. */
  runtime: Readonly<Record<RuntimeFileName, EngineFile>>;
  notices: readonly EngineFile[];
}

/**
 * The folder the runtime files are served from: assets/engine-<first 16 hex digits of a SHA-256 over every runtime file's name and
 * hash>. Content-addressed like Vite's own assets, so the folder can be cached forever (deploy/nginx caches assets/ for a year) and a
 * cached file can never belong to another engine.
 */
export function runtimeFolder(files: ReadonlyArray<{ name: string; integrity: string }>): string {
  const digest = createHash("sha256");
  for (const { name, integrity } of files) digest.update(`${name}\0${integrity}\0`);
  return `assets/engine-${digest.digest("hex").slice(0, 16)}`;
}

function readFile(dir: string, name: string): Uint8Array {
  const file = join(dir, name);
  if (!existsSync(file)) {
    throw new Error(
      `${file} is missing. Build the engine package with scripts/engine-package.sh (README.md, "Getting started").`,
    );
  }
  return readFileSync(file);
}

/** Reads the engine package and describes how the app serves it. Throws with instructions when the package is missing. */
export function readEngineBuild(dir: string = defaultPackageDir): EngineBuild {
  const commit = parsePin(new TextDecoder().decode(readFile(dir, "BUILT-FROM")), join(dir, "BUILT-FROM"));
  const manifest: unknown = JSON.parse(new TextDecoder().decode(readFile(dir, "package.json")));
  const version = (manifest as { version?: unknown }).version;
  if ((manifest as { name?: unknown }).name !== "@bayandocs/engine-wasm" || typeof version !== "string") {
    throw new Error(
      `${join(dir, "package.json")} does not describe bayan-core's engine package (@bayandocs/engine-wasm).`,
    );
  }
  const hashed = runtimeFileNames.map((name) => {
    const bytes = readFile(dir, name);
    return { name, bytes, integrity: integrityOf(bytes) };
  });
  const folder = runtimeFolder(hashed);
  const runtime = Object.fromEntries(
    hashed.map((file) => [file.name, { ...file, path: `${folder}/${file.name}` }]),
  ) as Record<RuntimeFileName, EngineFile>;
  const notices = noticeFileNames.map((name) => {
    const bytes = readFile(dir, name);
    return { name, bytes, integrity: integrityOf(bytes), path: `${noticesFolder}/${name}` };
  });
  return { commit, version, runtime, notices };
}

/** What the app's code learns about the engine at build time, through the module virtual:bayan-engine (src/engine/engine-files.d.ts). */
export function engineManifest(build: EngineBuild): EngineManifest {
  const entry = (file: EngineFile) => ({ url: `/${file.path}`, integrity: file.integrity });
  return {
    commit: build.commit,
    version: build.version,
    worker: entry(build.runtime["bayan-worker.js"]),
    glue: entry(build.runtime["bayan_wasm.js"]),
    wasm: entry(build.runtime["bayan_wasm_bg.wasm"]),
    notices: { url: `/${noticesFolder}/THIRD-PARTY-LICENSES.txt` },
  };
}
